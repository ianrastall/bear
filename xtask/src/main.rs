//! Developer tasks, run as `cargo xtask <task>`.

#![forbid(unsafe_code)]

mod sprt;
#[path = "../../crates/engine-core/src/attacks/tablegen.rs"]
mod tablegen;

use std::fmt::Write as _;
use std::path::Path;
use std::process::ExitCode;

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    match args.first().map(String::as_str) {
        Some("find-magics") => find_magics(),
        Some("sprt") => sprt::run_task(&args[1..]),
        _ => {
            eprintln!("usage: cargo xtask <task>");
            eprintln!();
            eprintln!("tasks:");
            eprintln!(
                "  find-magics   search for slider magic numbers and rewrite attacks/magics.rs"
            );
            eprintln!(
                "  sprt          test the working tree against an earlier revision with fastchess"
            );
            ExitCode::FAILURE
        }
    }
}

/// xorshift64*, seeded with a fixed value so the search is reproducible.
struct Rng(u64);

impl Rng {
    fn next(&mut self) -> u64 {
        self.0 ^= self.0 >> 12;
        self.0 ^= self.0 << 25;
        self.0 ^= self.0 >> 27;
        self.0.wrapping_mul(0x2545_F491_4F6C_DD1D)
    }

    /// A value with few set bits, which is what good magic numbers look like.
    fn sparse(&mut self) -> u64 {
        self.next() & self.next() & self.next()
    }
}

/// Finds a multiplier that maps every relevant occupancy of `sq` to a table slot with
/// no two different attack sets sharing a slot.
fn find_magic(sq: u8, rook: bool, rng: &mut Rng) -> u64 {
    let mask = if rook {
        tablegen::rook_mask(sq)
    } else {
        tablegen::bishop_mask(sq)
    };
    let bits = mask.count_ones();

    let mut cases = Vec::with_capacity(1 << bits);
    let mut subset = 0u64;
    loop {
        let attacks = if rook {
            tablegen::rook_attacks(sq, subset)
        } else {
            tablegen::bishop_attacks(sq, subset)
        };
        cases.push((subset, attacks));
        subset = subset.wrapping_sub(mask) & mask;
        if subset == 0 {
            break;
        }
    }

    let mut table = vec![0u64; 1 << bits];
    loop {
        let magic = rng.sparse();
        if (mask.wrapping_mul(magic) >> 56).count_ones() < 6 {
            continue;
        }
        table.fill(0);
        let fits = cases.iter().all(|&(occ, attacks)| {
            let slot = &mut table[(occ.wrapping_mul(magic) >> (64 - bits)) as usize];
            if *slot == 0 {
                *slot = attacks;
            }
            *slot == attacks
        });
        if fits {
            return magic;
        }
    }
}

fn write_array(out: &mut String, name: &str, values: &[u64; 64]) {
    writeln!(out, "#[rustfmt::skip]").unwrap();
    writeln!(out, "pub const {name}: [u64; 64] = [").unwrap();
    for row in values.chunks(4) {
        let cells: Vec<String> = row.iter().map(|v| format!("{v:#018x}")).collect();
        writeln!(out, "    {},", cells.join(", ")).unwrap();
    }
    writeln!(out, "];").unwrap();
}

fn find_magics() -> ExitCode {
    let mut rng = Rng(0x9E37_79B9_7F4A_7C15);
    let rook: [u64; 64] = std::array::from_fn(|sq| find_magic(sq as u8, true, &mut rng));
    let bishop: [u64; 64] = std::array::from_fn(|sq| find_magic(sq as u8, false, &mut rng));

    // Check the result the same way the build script will use it.
    let rook_entries = tablegen::magics(&rook, true, 0);
    let bishop_entries = tablegen::magics(&bishop, false, tablegen::ROOK_TABLE_SIZE);
    let mut table = vec![0u64; tablegen::SLIDER_TABLE_SIZE];
    tablegen::fill(&mut table, &rook_entries, true).expect("rook magics are collision-free");
    tablegen::fill(&mut table, &bishop_entries, false).expect("bishop magics are collision-free");

    let mut out = String::new();
    out.push_str("//! Magic multipliers for slider attack lookup.\n");
    out.push_str("//!\n");
    out.push_str("//! Generated by `cargo xtask find-magics`. Do not edit by hand.\n\n");
    write_array(&mut out, "ROOK_MAGICS", &rook);
    out.push('\n');
    write_array(&mut out, "BISHOP_MAGICS", &bishop);

    let path =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../crates/engine-core/src/attacks/magics.rs");
    match std::fs::write(&path, out) {
        Ok(()) => {
            println!("wrote {}", path.display());
            ExitCode::SUCCESS
        }
        Err(err) => {
            eprintln!("could not write {}: {err}", path.display());
            ExitCode::FAILURE
        }
    }
}
