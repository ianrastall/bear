//! Generates the attack lookup tables as Rust source in `OUT_DIR/tables.rs`.
//!
//! The tables are too large to evaluate in `const fn` without slowing every build, so
//! they are computed here with the same slow generator the unit tests compare against.

#[path = "src/attacks/magics.rs"]
mod magics;
#[path = "src/attacks/tablegen.rs"]
mod tablegen;

use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    println!("cargo::rerun-if-changed=build.rs");
    println!("cargo::rerun-if-changed=src/attacks/magics.rs");
    println!("cargo::rerun-if-changed=src/attacks/tablegen.rs");

    let rook = tablegen::magics(&magics::ROOK_MAGICS, true, 0);
    let bishop = tablegen::magics(&magics::BISHOP_MAGICS, false, tablegen::ROOK_TABLE_SIZE);
    assert_eq!(tablegen::table_end(&rook), tablegen::ROOK_TABLE_SIZE);
    assert_eq!(tablegen::table_end(&bishop), tablegen::SLIDER_TABLE_SIZE);

    let mut sliders = vec![0u64; tablegen::SLIDER_TABLE_SIZE];
    if let Err(sq) = tablegen::fill(&mut sliders, &rook, true) {
        panic!("rook magic for square {sq} has a collision; rerun `cargo xtask find-magics`");
    }
    if let Err(sq) = tablegen::fill(&mut sliders, &bishop, false) {
        panic!("bishop magic for square {sq} has a collision; rerun `cargo xtask find-magics`");
    }

    let mut out = String::with_capacity(3 << 20);
    out.push_str("// Generated by build.rs. Do not edit.\n\n");
    write_flat(&mut out, "SLIDERS", &sliders);
    write_pairs(&mut out, "BETWEEN", tablegen::between);
    write_pairs(&mut out, "LINE", tablegen::line);

    let path =
        PathBuf::from(std::env::var_os("OUT_DIR").expect("cargo sets OUT_DIR")).join("tables.rs");
    std::fs::write(&path, out).expect("OUT_DIR is writable");
}

fn write_flat(out: &mut String, name: &str, values: &[u64]) {
    writeln!(out, "pub static {name}: [u64; {}] = [", values.len()).unwrap();
    for row in values.chunks(8) {
        for value in row {
            write!(out, "{value:#x},").unwrap();
        }
        out.push('\n');
    }
    out.push_str("];\n\n");
}

fn write_pairs(out: &mut String, name: &str, f: fn(u8, u8) -> u64) {
    writeln!(out, "pub static {name}: [[u64; 64]; 64] = [").unwrap();
    for a in 0..64u8 {
        out.push('[');
        for b in 0..64u8 {
            write!(out, "{:#x},", f(a, b)).unwrap();
        }
        out.push_str("],\n");
    }
    out.push_str("];\n\n");
}
